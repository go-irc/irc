import urllib.request

import yaml

# Pinned commit of https://github.com/ircdocs/irc-defs
NUMERICS_COMMIT = "2dfd8956df1824e733022038fbac873f6b1ac03f"
NUMERICS_URL = (
    "https://raw.githubusercontent.com/ircdocs/irc-defs/"
    + NUMERICS_COMMIT
    + "/_data/numerics.yaml"
)

data = yaml.safe_load(urllib.request.urlopen(NUMERICS_URL))
vals = data["values"]

used = set()

print("// Code generated by utils/gen-numerics.py. DO NOT EDIT.")
print()
print("package irc")
print()
print("const (")
print("\t// Numerics are included if they're defined by RFC1459, RFC2812, or an")
print("\t// IRCv3 spec, or are in common use across servers.")
print()


def print_item(idx, item, ircv3=False, obsolete=None, **kwargs):
    if idx in used:
        return

    origin = item.get("origin", "")
    origin_name = kwargs.pop("origin", "")

    if ircv3:
        if "ircv3.net" not in item.get("contact", "") and "ircv3.net" not in item.get(
            "information", ""
        ):
            return
    elif origin_name and not origin or origin_name not in origin:
        return

    kwargs["obsolete"] = obsolete
    for k, v in kwargs.items():
        if item.get(k) != v:
            return

    # Mark seen
    used.add(idx)

    print("\t", end="")

    print('{} = "{}"'.format(item["name"], item["numeric"]), end="")

    if origin and origin != origin_name:
        print(" // {}".format(origin), end="")

    print()


def print_specific(**kwargs):
    """Print all numerics matching the given kwargs."""
    for index, item in enumerate(vals):
        print_item(index, item, **kwargs)


print("\t// RFC1459")
print_specific(origin="RFC1459")
print()
print("\t// RFC1459 (Obsolete)")
print_specific(origin="RFC1459", obsolete=True)
print()
print("\t// RFC2812")
print_specific(origin="RFC2812")
print()
print("\t// RFC2812 (Obsolete)")
print_specific(origin="RFC2812", obsolete=True)
print()
print("\t// IRCv3")
print_specific(origin="IRCv3", ircv3=True)
print()
# print('\t// IRCv3 (obsolete)')
# print_specific(origin='IRCv3', ircv3=True, obsolete=True)
# print()
print("\t// Other")
print_specific(name="RPL_ISUPPORT")

print(")")
